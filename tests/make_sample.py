#!/usr/bin/env python3
"""
Build a small synthetic PDF so the converter can be smoke-tested without
shipping anybody's real documents.

The page mimics the awkward parts of a real form: a tinted full-page background,
a photo-like block, and a QR-like checkerboard, plus text.
"""
import os
import random
import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 1240, 1754          # A4 at 150 dpi


def load_font(size):
    for name in ("arial.ttf", "DejaVuSans.ttf", "segoeui.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def main(path):
    random.seed(7)
    im = Image.new("RGB", (W, H), "white")
    d = ImageDraw.Draw(im)

    # faint full-page tint, like an anti-counterfeit wash
    for y in range(0, H, 6):
        d.line([(0, y), (W, y)], fill=(246, 250, 249), width=1)

    d.rectangle([20, 20, W - 20, H - 20], outline=(0, 120, 100), width=3)
    f_title = load_font(46)
    f_body = load_font(26)
    d.text((90, 90), "SAMPLE VERIFICATION REPORT", font=f_title, fill=(10, 10, 10))
    d.text((90, 160), "generated by make_sample.py - no real data", font=load_font(20), fill=(90, 90, 90))

    rows = [("Name", "ZHANG SAN"), ("Sex", "M"), ("Date of birth", "2000-01-01"),
            ("School", "EXAMPLE UNIVERSITY"), ("Major", "ELECTRICAL ENGINEERING"),
            ("Level", "MASTER"), ("Status", "ENROLLED")]
    y = 260
    for k, v in rows:
        d.text((90, y), k, font=f_body, fill=(40, 40, 40))
        d.text((380, y), v, font=f_body, fill=(10, 10, 10))
        y += 58

    # photo block
    d.rectangle([930, 250, 1090, 460], fill=(190, 225, 245), outline=(120, 160, 190))
    d.ellipse([960, 300, 1040, 380], fill=(225, 190, 165))

    # QR-like block
    qx, qy, cell = 100, 1300, 7
    for gy in range(28):
        for gx in range(28):
            if (gx * 7 + gy * 13 + gx * gy) % 3 == 0 or gx in (0, 27) or gy in (0, 27):
                d.rectangle([qx + gx * cell, qy + gy * cell,
                             qx + (gx + 1) * cell - 1, qy + (gy + 1) * cell - 1], fill=(0, 0, 0))

    d.text((330, 1330), "VERIFICATION CODE  ABCD-1234-EFGH", font=load_font(22), fill=(10, 10, 10))
    d.text((330, 1380), "https://example.com/verify", font=load_font(20), fill=(10, 10, 10))
    for i in range(4):
        d.text((90, 1500 + i * 34), "note %d: this paragraph exists to add text density to the page" % (i + 1),
               font=load_font(18), fill=(30, 30, 30))

    im.save(path, "PDF", resolution=150.0)
    print("wrote", path, os.path.getsize(path), "bytes")


if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 else "sample.pdf"
    parent = os.path.dirname(os.path.abspath(target))
    os.makedirs(parent, exist_ok=True)
    sys.exit(main(target))
